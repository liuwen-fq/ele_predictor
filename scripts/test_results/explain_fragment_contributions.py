"""Summarize additive fragment contributions and interactions.

The input can use either the residual contribution head or the independent
condition-aware explanation head generated by ``predict.py``.  For the
independent head, fragment effects are additive around a learned condition
reference rather than altering the deployed Bamboo prediction.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean

from explain_experimental_fragments import (classify_functional_group,
                                            conductivity_ms_cm, percentile)


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        path.write_text("")
        return
    with path.open("w", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def odds_ratio(high_present: int, high_total: int, low_present: int,
               low_total: int) -> float:
    return ((high_present + 0.5) * (low_total - low_present + 0.5) /
            ((high_total - high_present + 0.5) * (low_present + 0.5)))


def selected_records(records: list[dict], contribution_key: str) -> list[dict]:
    selected = []
    for index, record in enumerate(records):
        if not record.get("conductivity_mask", False):
            continue
        if contribution_key not in record:
            raise ValueError(
                f"{contribution_key} is missing; run contribution-aware "
                "prediction first")
        selected.append({
            "sample_index": index,
            "target": conductivity_ms_cm(float(record["conductivity"])),
            "record": record,
        })
    if not selected:
        raise ValueError("no experimental conductivity records were found")
    return selected


def annotate_groups(samples: list[dict], quantile: float):
    values = [sample["target"] for sample in samples]
    low_cutoff = percentile(values, quantile)
    high_cutoff = percentile(values, 1 - quantile)
    for sample in samples:
        if sample["target"] <= low_cutoff:
            sample["group"] = "low"
        elif sample["target"] >= high_cutoff:
            sample["group"] = "high"
        else:
            sample["group"] = "middle"
    return low_cutoff, high_cutoff


def collect_formula_rows(samples: list[dict], contribution_key: str):
    group_rows = []
    solvent_rows = []
    pair_rows = []
    for sample in samples:
        record = sample["record"]
        group_effects = defaultdict(float)
        group_structures = defaultdict(Counter)
        solvent_effects = defaultdict(float)
        solvent_groups = defaultdict(Counter)
        solvent_smiles = {}
        solvent_ratios = {
            solvent["name"]: float(solvent.get("molar_ratio", 0.0))
            for solvent in record.get("solvents", [])
        }
        for molecule in record.get("fragment_attention", {}).get(
                "solvents", []):
            molecule_name = molecule.get("molecule_name", "unknown")
            solvent_smiles[molecule_name] = molecule.get("mapped_smiles", "")
            for fragment in molecule.get("fragments", []):
                if "conductivity_main_effect_normalized" not in fragment:
                    continue
                fragment_smiles = fragment.get("smiles", "")
                functional_group = classify_functional_group(
                    fragment_smiles)["functional_group"]
                effect = float(
                    fragment["conductivity_main_effect_normalized"])
                group_effects[functional_group] += effect
                group_structures[functional_group][fragment_smiles] += 1
                solvent_effects[molecule_name] += effect
                solvent_groups[molecule_name][functional_group] += 1
        for functional_group, effect in group_effects.items():
            group_rows.append({
                "sample_index": sample["sample_index"],
                "conductivity_group": sample["group"],
                "functional_group": functional_group,
                "effect": effect,
                "representative_fragment": group_structures[
                    functional_group].most_common(1)[0][0],
            })
        for molecule_name, effect in solvent_effects.items():
            solvent_rows.append({
                "sample_index": sample["sample_index"],
                "conductivity_group": sample["group"],
                "molecule_name": molecule_name,
                "molecule_smiles": solvent_smiles.get(molecule_name, ""),
                "molar_ratio": solvent_ratios.get(molecule_name, 0.0),
                "effect": effect,
                "functional_groups": "；".join(
                    group for group, _ in solvent_groups[
                        molecule_name].most_common()),
            })
        for pair in record[contribution_key].get(
                "top_fragment_pairs", []):
            left = pair["left"]
            right = pair["right"]
            left_group = classify_functional_group(
                left.get("fragment_smiles", ""))["functional_group"]
            right_group = classify_functional_group(
                right.get("fragment_smiles", ""))["functional_group"]
            group_a, group_b = sorted((left_group, right_group))
            pair_rows.append({
                "sample_index": sample["sample_index"],
                "conductivity_group": sample["group"],
                "functional_group_a": group_a,
                "functional_group_b": group_b,
                "molecule_a": left.get("molecule_name", ""),
                "molecule_b": right.get("molecule_name", ""),
                "effect": float(pair["effect_normalized"]),
            })
    return group_rows, solvent_rows, pair_rows


def summarize_groups(rows: list[dict], samples: list[dict]):
    grouped = defaultdict(list)
    for row in rows:
        grouped[row["functional_group"]].append(row)
    high_ids = {sample["sample_index"] for sample in samples
                if sample["group"] == "high"}
    low_ids = {sample["sample_index"] for sample in samples
               if sample["group"] == "low"}
    output = []
    for group, values in grouped.items():
        effects = {row["sample_index"]: row["effect"] for row in values}
        high_values = [effects.get(index, 0.0) for index in high_ids]
        low_values = [effects.get(index, 0.0) for index in low_ids]
        present = list(effects.values())
        structures = Counter(row["representative_fragment"] for row in values)
        output.append({
            "functional_group": group,
            "unique_formulas": len(effects),
            "high_formula_count": sum(index in effects for index in high_ids),
            "low_formula_count": sum(index in effects for index in low_ids),
            "mean_effect_when_present_normalized": mean(present),
            "positive_effect_fraction_when_present": sum(
                value > 0 for value in present) / len(present),
            "high_mean_effect_all_formulas_normalized": mean(high_values),
            "low_mean_effect_all_formulas_normalized": mean(low_values),
            "high_minus_low_effect_normalized": mean(high_values) - mean(
                low_values),
            "representative_fragment_smiles": structures.most_common(1)[0][0],
        })
    return sorted(output,
                  key=lambda row: abs(row[
                      "mean_effect_when_present_normalized"]), reverse=True)


def summarize_solvents(rows: list[dict], samples: list[dict]):
    grouped = defaultdict(list)
    for row in rows:
        grouped[(row["molecule_name"], row["molecule_smiles"])].append(row)
    high_total = sum(sample["group"] == "high" for sample in samples)
    low_total = sum(sample["group"] == "low" for sample in samples)
    output = []
    for (name, smiles), values in grouped.items():
        high = [row for row in values if row["conductivity_group"] == "high"]
        low = [row for row in values if row["conductivity_group"] == "low"]
        effects = [row["effect"] for row in values]
        high_count, low_count = len(high), len(low)
        association = odds_ratio(high_count, high_total, low_count, low_total)
        output.append({
            "molecule_name": name,
            "molecule_smiles": smiles,
            "functional_groups": Counter(
                row["functional_groups"] for row in values).most_common(1)[0][0],
            "unique_formulas": len(values),
            "high_formula_count": high_count,
            "low_formula_count": low_count,
            "high_vs_low_presence_odds_ratio": association,
            "mean_molar_ratio_when_present": mean(
                row["molar_ratio"] for row in values),
            "mean_signed_effect_normalized": mean(effects),
            "positive_effect_fraction": sum(value > 0 for value in effects) /
            len(effects),
            "screening_label": (
                "高电导率候选溶剂" if association > 1 and mean(effects) > 0
                else "低电导率待避开候选" if association < 1 and mean(effects) < 0
                else "统计关联与模型贡献不一致"),
        })
    return sorted(output,
                  key=lambda row: abs(math.log(row[
                      "high_vs_low_presence_odds_ratio"])), reverse=True)


def summarize_pairs(rows: list[dict]):
    grouped = defaultdict(list)
    for row in rows:
        grouped[(row["functional_group_a"],
                 row["functional_group_b"])].append(row)
    output = []
    for (group_a, group_b), values in grouped.items():
        effects = [row["effect"] for row in values]
        high = [row["effect"] for row in values
                if row["conductivity_group"] == "high"]
        low = [row["effect"] for row in values
               if row["conductivity_group"] == "low"]
        effect = mean(effects)
        output.append({
            "functional_group_a": group_a,
            "functional_group_b": group_b,
            "top_pair_occurrences": len(values),
            "unique_formulas": len({row["sample_index"] for row in values}),
            "mean_interaction_effect_normalized": effect,
            "positive_interaction_fraction": sum(value > 0 for value in effects)
            / len(effects),
            "high_group_mean_interaction_normalized": mean(high) if high else "",
            "low_group_mean_interaction_normalized": mean(low) if low else "",
            "model_interaction_label": (
                "模型正协同候选" if effect > 0 else "模型拮抗候选"),
        })
    return sorted(output,
                  key=lambda row: abs(row[
                      "mean_interaction_effect_normalized"]), reverse=True)


def main():
    parser = argparse.ArgumentParser(
        description="Analyze signed conductivity fragment contributions")
    parser.add_argument("--input", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--contribution-key", default="fragment_contributions")
    parser.add_argument("--quantile", type=float, default=0.25)
    args = parser.parse_args()
    if not 0 < args.quantile < 0.5:
        raise ValueError("--quantile must be in (0, 0.5)")

    records = json.loads(Path(args.input).read_text())
    samples = selected_records(records, args.contribution_key)
    low_cutoff, high_cutoff = annotate_groups(samples, args.quantile)
    group_rows, solvent_rows, pair_rows = collect_formula_rows(
        samples, args.contribution_key)
    group_summary = summarize_groups(group_rows, samples)
    solvent_summary = summarize_solvents(solvent_rows, samples)
    pair_summary = summarize_pairs(pair_rows)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    write_csv(output_dir / "functional_group_signed_contributions.csv",
              group_summary)
    write_csv(output_dir / "solvent_candidate_summary.csv", solvent_summary)
    write_csv(output_dir / "fragment_pair_signed_interactions.csv", pair_summary)
    report = [
        "# 条件感知片段贡献分析",
        "",
        f"实验样本数：{len(samples)}",
        f"低电导率阈值：{low_cutoff:.6g} mS/cm",
        f"高电导率阈值：{high_cutoff:.6g} mS/cm",
        "",
        "单片段贡献和片段对交互是条件化组成解释中的有符号加和项；正值提高解释分数，负值降低解释分数。",
        "片段对表只汇总每条配方保存的绝对值最大的若干交互项。数据富集仍是观察性关联，不能替代实验因果验证。",
        "",
        "详细结果见 `functional_group_signed_contributions.csv`、`solvent_candidate_summary.csv` 和 `fragment_pair_signed_interactions.csv`。",
    ]
    (output_dir / "interpretation_report.md").write_text(
        "\n".join(report) + "\n")
    print(f"Wrote signed fragment contribution analysis to: {output_dir}")


if __name__ == "__main__":
    main()
